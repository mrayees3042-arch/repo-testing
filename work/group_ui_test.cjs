await page.getByRole('checkbox',{name:'Select Temperature for a group'}).check();
await page.getByRole('button',{name:'Group selected tags'}).click();
await page.locator('#group-count').filter({hasText:'2 tags selected'}).waitFor();
await page.getByLabel('Group name',{exact:true}).fill('Cooling overview');
await page.getByRole('button',{name:'Save group',exact:true}).click();
await page.locator('.live-card').first().waitFor();console.log('created group');assert.equal(await page.locator('.live-card').count(),2);
// Table monitoring may continue while a group is paused; its UI must still freeze.
await page.evaluate(async()=>{const tables=await window.pywebview.api.get_all_tables();await window.pywebview.api.set_polling(true,tables.find(t=>t.name==='Cooling').id);});
await page.getByRole('button',{name:'Start live view',exact:true}).click();
await page.locator('.live-card[data-quality="GOOD"]').first().waitFor();
await page.locator('.card-trend svg').first().waitFor();
const traces=page.locator('.card-trend svg path:last-of-type');
const graphBefore=await traces.nth(1).getAttribute('d');
console.log('live graph visible');const value=await page.locator('.card-value').nth(1).textContent();
await page.waitForFunction(v=>document.querySelectorAll('.card-value')[1].textContent!==v,value);
await page.waitForFunction(d=>document.querySelectorAll('.card-trend svg path:last-of-type')[1]?.getAttribute('d')!==d,graphBefore);
await page.getByRole('button',{name:'Pause live view'}).click();
await page.locator('.live-card[data-quality="STALE"]').first().waitFor();
console.log('paused');const pausedGraph=await traces.allTextContents();
const pausedPaths=await traces.evaluateAll(els=>els.map(e=>e.getAttribute('d')));
const paused=await page.locator('.card-value').allTextContents();await page.waitForTimeout(1600);
assert.deepEqual(await page.locator('.card-value').allTextContents(),paused);
assert.deepEqual(await traces.evaluateAll(els=>els.map(e=>e.getAttribute('d'))),pausedPaths);
await page.getByRole('button',{name:'Customize',exact:true}).click();
await page.getByLabel('Group name',{exact:true}).fill('Plant overview');
await page.locator('.group-choice').filter({hasText:'Pump running'}).locator('input').uncheck();
