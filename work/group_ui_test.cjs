await page.locator('.group-choice').filter({hasText:'Motor count'}).locator('input').check();
await page.getByRole('button',{name:'Save group',exact:true}).click();
await page.waitForFunction(()=>document.querySelector('#group-select').selectedOptions[0]?.textContent==='Plant overview');
await page.waitForFunction(()=>document.querySelector('#group-cards').textContent.includes('Motor count'));
assert.equal(await page.locator('.live-card').count(),2);
assert(!(await page.locator('#group-cards').textContent()).includes('Pump running'));

await page.getByRole('button',{name:'Start live view',exact:true}).click();
await page.locator('.live-card[data-quality="GOOD"]').first().waitFor();
await page.waitForFunction(()=>document.querySelector('.card-trend svg path:last-of-type')?.getAttribute('d').split('M').length>=3);
await page.evaluate(()=>window.pywebview.api.test_connection(false));
await page.locator('.live-card[data-quality="STALE"]').first().waitFor();
await page.locator('#group-status').filter({hasText:'Disconnected'}).waitFor();
await page.getByRole('button',{name:'Switch to day mode'}).click();
await page.waitForFunction(()=>document.documentElement.dataset.theme==='light');
console.log('theme and edit passed');await page.reload();await page.getByRole('tab',{name:'Live Groups',exact:true}).click();
await page.locator('.live-card').first().waitFor();
