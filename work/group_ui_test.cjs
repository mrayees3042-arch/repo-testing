global.testPage=page; page.setDefaultTimeout(12000);
const errors=[];page.on('pageerror',e=>errors.push(String(e)));
await page.addInitScript(()=>{
 window.pywebview={api:new Proxy({}, {get:(_,method)=>method==='then'?undefined:(...args)=>fetch('/api/'+String(method),{method:'POST',headers:{'Content-Type':'application/json'},body:JSON.stringify(args)}).then(async r=>{const data=await r.json();if(!r.ok)throw Error(data.error);return data;})})};
});
const url='http://127.0.0.1:'+fs.readFileSync('work/ui_test_port.txt','utf8').trim();
await page.goto(url);await page.getByRole('tab',{name:'Tag Tables',exact:true}).click();
