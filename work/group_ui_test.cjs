assert.equal(await page.locator('.tag-pick').count(),2);
assert.deepEqual(errors,[]);
console.log('PASS: selection, group save, changing live values, pause, rename, cross-table membership edits, disconnect/stale, theme reload, 800px layout, Escape, delete preserves source tags, no JS errors.');
